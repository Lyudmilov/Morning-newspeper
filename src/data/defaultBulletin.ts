export function getLiveBulgarianDateStr(): string {
  return new Intl.DateTimeFormat('bg-BG', {
    day: 'numeric',
    month: 'long',
    year: 'numeric',
  }).format(new Date());
}

export function getLiveBulgarianTimestamp(): string {
  const d = new Date();
  const dateStr = getLiveBulgarianDateStr();
  const timeStr = d.toLocaleTimeString('bg-BG', { hour: '2-digit', minute: '2-digit', second: '2-digit' });
  return `${dateStr}, ${timeStr} ч.`;
}

